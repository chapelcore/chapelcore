// generate-types.ts — writes the TS core's types from the contract's JSON Schemas.
// Why: the types must match the contract exactly (phase-1.md §6.4, E1). Generating them
// means nobody writes them by hand, and a test can regenerate them and compare.
// How it connects: `pnpm --filter @chapelcore/core generate` runs this file with Node. It
// reads every schema in @chapelcore/contract and writes src/generated/contract.ts (from
// json-schema-to-typescript) and src/types.ts (each type wrapped in DeepReadonly), both
// formatted with the repository's Prettier settings. tests/types.test.ts calls
// generateTypes() to check that the committed files are up to date.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import { format, resolveConfig } from 'prettier';

const CORE_ROOT = fileURLToPath(new URL('../', import.meta.url));
const CONTRACT_ROOT = dirname(
  fileURLToPath(import.meta.resolve('@chapelcore/contract/package.json')),
);

export const SCHEMAS_DIR = join(CONTRACT_ROOT, 'schemas');
export const FIXTURES_DIR = join(CONTRACT_ROOT, 'fixtures');
export const CONTRACT_FILE = join(CORE_ROOT, 'src', 'generated', 'contract.ts');
export const TYPES_FILE = join(CORE_ROOT, 'src', 'types.ts');

interface Schema {
  /** File name without `.schema.json`, e.g. `health-status`; also its fixtures' folder. */
  readonly name: string;
  /** The schema's `title`, e.g. `HealthStatus`; also the TypeScript type's name. */
  readonly title: string;
  readonly description: string;
}

/** Every contract schema, sorted by file name. */
export function readSchemas(): Schema[] {
  return readdirSync(SCHEMAS_DIR)
    .filter((file) => file.endsWith('.schema.json'))
    .sort()
    .map((file) => {
      const schema = JSON.parse(readFileSync(join(SCHEMAS_DIR, file), 'utf8')) as {
        title: string;
        description: string;
      };
      return {
        name: file.slice(0, -'.schema.json'.length),
        title: schema.title,
        description: schema.description,
      };
    });
}

const CONTRACT_HEADER = `// contract.ts — GENERATED from libs/shared/contract/schemas by scripts/generate-types.ts.
// Do not edit: change the schema, then run \`pnpm --filter @chapelcore/core generate\`.
// Why: one interface per schema, so TypeScript and the contract can't disagree.
// How it connects: src/types.ts re-exports each one as read-only; nothing else imports
// this file.
`;

const TYPES_HEADER = `// types.ts — GENERATED by scripts/generate-types.ts. Do not edit; run
// \`pnpm --filter @chapelcore/core generate\`.
// Why: transport objects are values (DOMAIN-MODEL universal rule 8), so every contract
// type is exported read-only, at every depth (phase-1.md §6.4, E1).
// How it connects: src/index.ts exports everything here; the types come from
// src/generated/contract.ts.

import type { Contract } from './generated/contract.js';

/** Makes every field and list read-only, at every depth. */
export type DeepReadonly<T> = T extends readonly (infer Item)[]
  ? readonly DeepReadonly<Item>[]
  : T extends object
    ? { readonly [K in keyof T]: DeepReadonly<T[K]> }
    : T;
`;

/** The text of both generated files, formatted, without writing anything. */
export async function generateTypes(): Promise<{ contract: string; types: string }> {
  const schemas = readSchemas();

  // One wrapper schema that points at every file, so each type is generated exactly once.
  const wrapper: JSONSchema = {
    title: 'Contract',
    description: 'Every contract type by name; src/types.ts reads its types from here.',
    type: 'object',
    additionalProperties: false,
    required: schemas.map((schema) => schema.title),
    properties: Object.fromEntries(
      schemas.map((schema) => [schema.title, { $ref: `${schema.name}.schema.json` }]),
    ),
  };
  const body = await compile(wrapper, 'Contract', {
    cwd: SCHEMAS_DIR,
    bannerComment: '',
    format: false,
    additionalProperties: false,
  });

  const exports = schemas.map(
    (schema) =>
      `\n/** ${schema.description} */\nexport type ${schema.title} = DeepReadonly<Contract['${schema.title}']>;\n`,
  );

  const options = (await resolveConfig(TYPES_FILE)) ?? {};
  return {
    contract: await format(CONTRACT_HEADER + '\n' + body, { ...options, parser: 'typescript' }),
    types: await format(TYPES_HEADER + exports.join(''), { ...options, parser: 'typescript' }),
  };
}

// Run as a script: write both files.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { contract, types } = await generateTypes();
  mkdirSync(dirname(CONTRACT_FILE), { recursive: true });
  writeFileSync(CONTRACT_FILE, contract);
  writeFileSync(TYPES_FILE, types);
  console.log(`Wrote ${CONTRACT_FILE}\nWrote ${TYPES_FILE}`);
}
